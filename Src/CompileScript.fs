    let green  msg = IFeshLog.log.PrintfnColor 0   140 0 msg
    let black  msg = IFeshLog.log.PrintfnColor 0   0   0 msg
    let gray   msg = IFeshLog.log.PrintfnColor 190 190 190 msg
