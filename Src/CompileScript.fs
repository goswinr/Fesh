module CompileScript =

    /// also removes "_" ;  "-" ; "+"; "|"; " " from string
    /// first letter will be capital
    let toCamelCase (s:string) =
        // TODO the result is used as namespace and file name, but is not always a valid identifier:
        // "Script (1)" gives "script(1)", "2024-beam" gives "2024Beam" (leading digit). Keep only letters and digits, prefix "_" if it starts with a digit.
        // TODO s.[0] throws on an empty string, and the result is empty if s has only separators
        s.Split([|"_" ;  "-" ; "+"; "|"; " "|], StringSplitOptions.RemoveEmptyEntries) // keep dot?!
        |> Array.map Str.up1
        |> String.concat ""
        |> (fun x -> if Char.IsLower s.[0] then Str.low1 x else x)

    let replace (a:string) (b:string) (s:string) = s.Replace(a,b) // TODO duplicate of Str.replace

    type DllRef = {fullPath:string option; fileName:string; nameNoExt:string; copyLocal:bool}
    /// code is the content of the loaded file with its #r and #load lines commented out
    type FsxRef = {fullPath:string; fileName:string; code:string}
    type NugetRef = {name:string; version:string}

    /// Resolves a path from a #r or #load line against the folder of the file that contains it, like FSI does.
    /// (Path.Combine returns the second path unchanged if it is already absolute.)
    let resolvePath (dir:string) (path:string) =
        Path.GetFullPath(Path.Combine(dir, path)).Replace('\\','/')

    /// Comments out all #r and #load lines and collects what they reference.
    /// Files from #load are processed recursively too.
    /// They are added to the fsx list before the file that loads them, so they compile first.
    let extractRefs(code:string, scriptPath:string, nameSpace:string) : ResizeArray<DllRef>*ResizeArray<FsxRef>*ResizeArray<NugetRef>*string=
        let refs = ResizeArray<DllRef>()
        let nugs = ResizeArray<NugetRef>()
        let fsxs = ResizeArray<FsxRef>()
        let visited = Collections.Generic.HashSet<string>(StringComparer.OrdinalIgnoreCase) // to load each file only once, and to avoid cycles
        visited.Add (Path.GetFullPath(scriptPath).Replace('\\','/')) |> ignore

        let addRef (r:DllRef) =
            if not (refs.Exists(fun x -> x.fileName.Equals(r.fileName, StringComparison.OrdinalIgnoreCase))) then refs.Add r
        let addNug (n:NugetRef) =
            match nugs.FindIndex(fun x -> x.name.Equals(n.name, StringComparison.OrdinalIgnoreCase)) with
            | -1 -> nugs.Add n
            | i  -> if nugs[i].version = "*" then nugs[i] <- n // prefer an explicit version over the floating one

        let rec processCode (code:string, dir:string, header:string option) : string =
            let codeWithoutRefs = StringBuilder()
            codeWithoutRefs.AppendLine "// This file is generated by Fesh. Manual edits will get lost when regenerated." |> ignore
            header |> Option.iter (fun h -> codeWithoutRefs.AppendLine h |> ignore)
            for ln in code.Split('\n') do
                let tln = ln.Trim()
                if tln.StartsWith "#r \"nuget" then
                    codeWithoutRefs.Append "// "  |> ignore
                    match Str.between "nuget:" "\"" tln with
                    |None -> ()
                    |Some pkgV ->
                        let pkg,version =
                            if pkgV.Contains(",")then       pkgV |> Str.splitOnce ","
                            else                            pkgV, "*"
                        addNug {name=pkg.Trim(); version=version.Trim()}

                elif tln.StartsWith "#r " then
                    codeWithoutRefs.Append "// "  |> ignore
                    let _,path,_ = Str.splitTwice "\""  "\"" tln // get part in quotes
                    if path <> "" then
                        let stPath = path.Replace ('\\','/')
                        if stPath.Contains "/RhinoCommon.dll" then
                            addRef {fullPath= Some (resolvePath dir path); fileName="RhinoCommon.dll" ;nameNoExt="RhinoCommon"  ;  copyLocal=false}

                        elif stPath.Contains "/" || File.Exists(Path.Combine(dir, path)) then // a path, or a dll next to the script
                            let fileName = Path.GetFileName path
                            let nameNoExt = fileName.Replace(".dll", "") // TODO make case insensitive, cover .exe
                            addRef { fullPath=Some (resolvePath dir path); fileName=fileName ;nameNoExt=nameNoExt; copyLocal=true}
                        else
                            let nameNoExt = path.Replace(".dll", "") // TODO make case insensitive, cover .exe
                            addRef { fullPath=None; fileName=path ;nameNoExt=nameNoExt; copyLocal=false} // for BCL dlls of the .Net framework

                elif tln.StartsWith "#load " then
                    codeWithoutRefs.Append "// "  |> ignore
                    let _,path,_ = Str.splitTwice "\""  "\"" tln
                    if path <> "" then
                        let fullPath = resolvePath dir path
                        if visited.Add fullPath then
                            // TODO loaded files get no header, so one without its own top level 'module' or 'namespace' line fails with FS0222
                            let loadedCode = processCode (File.ReadAllText fullPath, Path.GetDirectoryName fullPath, None)
                            fsxs.Add {fullPath=fullPath; fileName=Path.GetFileName fullPath; code=loadedCode}

                // TODO other script only directives are not commented out yet: #I (then a bare #r "Foo.dll" from that folder is unresolved), #i "nuget:...", #time, #help, #quit

                codeWithoutRefs.AppendLine (ln.TrimEnd()) |> ignore
            codeWithoutRefs.ToString()

        // TODO because of this namespace line, scripts that start with their own top level 'module' or 'namespace', or have top level 'let's, fail to compile.
        // The compiler error does not say why. Detect a leading 'module' or 'namespace' line and skip the header, or log a hint.
        let mainCode = processCode (code, Path.GetDirectoryName scriptPath, Some $"namespace {nameSpace}")
        refs, fsxs, nugs, mainCode

    //if last write is more than half an hour ago ask for overwrite permissions
    // TODO this is called from inside an async, so return Async<bool> and use let! instead of Async.RunSynchronously
    // TODO when the user answers No nothing is logged, log that the compilation was skipped
    let overWriteExisting fsProj :bool=
        async{
            do! Async.SwitchToContext Fittings.SyncWpf.context
            let maxAgeHours = 0.5
            let fi = FileInfo(fsProj)
            return
                if fi.Exists then
                    let age = DateTime.UtcNow - fi.LastWriteTimeUtc
                    if age > (TimeSpan.FromHours maxAgeHours) then
                        let msg = sprintf "Do you want to recompile and overwrite the existing files?\r\n \r\n%s\r\n \r\nthat are %.2f days old at\r\n \r\n(This dialog only shows if the last compilation was more than %.1f hours ago.)"fi.FullName age.TotalDays  maxAgeHours
                        //match MessageBox.Show(msg, StyleState.dialogCaption, MessageBoxButtons.YesNo, MessageBoxIcon.Exclamation, MessageBoxDefaultButton.Button2) with  // uses Windows.Forms
                        match MessageBox.Show(
                            IEditor.mainWindow,
                            msg,
                            "Fesh | Recompile and overwrite?",
                            MessageBoxButton.YesNo,
                            MessageBoxImage.Exclamation,
                            MessageBoxResult.No,// default result
                            MessageBoxOptions.None) with
                        | MessageBoxResult.Yes-> true
                        | MessageBoxResult.No-> false
                        | _ -> false
                    else
                        true
                else
                    true
        }|>  Async.RunSynchronously

    // TODO getNugsXml and getRefsXml do not XML-escape names and paths, an '&' in a dll file name or in the RhinoCommon path gives MSB4025. Use SecurityElement.Escape.
    let getNugsXml (nugs:ResizeArray<NugetRef>) : string =
           seq{ for nug in nugs  do  "<PackageReference Include=\"" + nug.name + "\" Version=\"" + nug.version + "\" />" }
           |> String.concat (Environment.NewLine  + String(' ',4) )

    /// Also copies the dlls with copyLocal=true to the lib folder.
    /// TODO the copying happens lazily, inside the seq consumed by String.concat. Do it in a separate step before building the XML.
    let getRefsXml (libFolderFull:string,  refs:ResizeArray<DllRef>) : string=
        seq{
            for ref in refs |> Seq.sortBy (fun r -> if r.fullPath.IsNone then 0 else 1) do
                match ref.fullPath with
                | None -> // for BCL dlls of the .Net framework
                    "<Reference Include=\"" + ref.nameNoExt + "\" />"
                |Some fPath ->
                    if ref.copyLocal then
                        let newp = IO.Path.Combine(libFolderFull, ref.fileName)
                        if IO.File.Exists newp then IO.File.Delete newp
                        IO.File.Copy(fPath,newp )

                        let xml  = Path.ChangeExtension(fPath,"xml")
                        let xmln = Path.ChangeExtension(newp,"xml")
                        if IO.File.Exists xmln then IO.File.Delete xmln
                        if IO.File.Exists (xml) then IO.File.Copy(xml, xmln)

                        let pdb  = Path.ChangeExtension(fPath,"pdb")
                        let pdbn = Path.ChangeExtension(newp,"pdb")
                        if IO.File.Exists pdbn then IO.File.Delete pdbn
                        if IO.File.Exists (pdb) then IO.File.Copy(pdb, pdbn)
                        "<Reference Include=\"" + ref.nameNoExt + "\"><HintPath>" + ScriptCompilerFsproj.LibFolderName + "/" + ref.fileName + "</HintPath></Reference>"

                    else
                        "<Reference Include=\"" + ref.nameNoExt + "\"><HintPath>" + fPath + "</HintPath><Private>False</Private></Reference>"
        }
        |> String.concat (Environment.NewLine  + String(' ',4) )

    let getFsxXml (projFolder:string, nameSpace:string, code:string, fsxloads:ResizeArray<FsxRef>) : string=
        seq{
            for load in fsxloads do
                // TODO two loaded files with the same name from different folders overwrite each other here, and could also collide with the main {nameSpace}.fs
                let niceName = (Path.GetFileNameWithoutExtension load.fileName |> toCamelCase  ) + ".fs"
                IO.File.WriteAllText(IO.Path.Combine(projFolder,niceName), load.code, Text.Encoding.UTF8)
                yield "<Compile Include=\"" + niceName + "\" />"

            let fsxName = nameSpace + ".fs"
            let fsxPath = IO.Path.Combine(projFolder,fsxName)
            IO.File.WriteAllText(fsxPath,code,Text.Encoding.UTF8)
            yield     "<Compile Include=\"" + fsxName + "\" />"
        }
        |> String.concat (Environment.NewLine + String(' ',4) )


